/**
 * Runs T01–T10 in order and prints a pass/fail report.
 *
 *   pnpm scenarios                       # in-process, real OpenAI (needs OPENAI_API_KEY)
 *   pnpm scenarios --url http://localhost:3000   # against a running server's POST /chat
 *   pnpm scenarios --offline             # LLM replaced by fixture intents (no key needed)
 *   pnpm scenarios --keep                # do not reset the database first
 */
import "./load-env";
import { mkdirSync, writeFileSync } from "node:fs";
import { awaitAllCallbacks } from "@langchain/core/callbacks/promises";
import type { AgentDeps, ChatResult } from "@/lib/agent/types";
import { resetDatabase } from "@/lib/db/client";
import { now } from "@/lib/env";
import { checkScenario, SCENARIOS } from "@/lib/scenarios";

const args = process.argv.slice(2);
const urlIndex = args.indexOf("--url");
const baseUrl = urlIndex >= 0 ? args[urlIndex + 1] : null;
const offline = args.includes("--offline");
const keep = args.includes("--keep");

async function offlineDeps(): Promise<AgentDeps> {
  const { fakeDeps, SCENARIO_INTENTS } = await import("../tests/helpers/fixtures");
  return fakeDeps(Object.fromEntries(SCENARIOS.map((s) => [s.message, SCENARIO_INTENTS[s.id]])));
}

async function send(userId: number, message: string, deps?: AgentDeps): Promise<ChatResult> {
  if (baseUrl) {
    const res = await fetch(new URL("/chat", baseUrl), {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ user_id: userId, message }),
    });
    const json = await res.json();
    return { ...json, task_id: json.task_id ?? undefined };
  }
  const { handleChat } = await import("@/lib/chat/handle-chat");
  return handleChat({ userId, message, channel: "script" }, deps);
}

if (!baseUrl && !offline && !process.env.OPENAI_API_KEY) {
  console.error("OPENAI_API_KEY is missing. Add it to .env, or run with --offline / --url.");
  process.exit(1);
}

if (!keep) {
  if (baseUrl) {
    const res = await fetch(new URL("/api/reset", baseUrl), { method: "POST" });
    if (!res.ok) console.warn("! Could not reset the server database (ENABLE_DEMO_RESET is off); results may include older tasks.");
  } else {
    await resetDatabase();
  }
}

const deps = offline ? await offlineDeps() : undefined;
const today = now();
const results: Record<string, ChatResult> = {};
const rows: string[] = [];
let passed = 0;

const mode = baseUrl ? `HTTP ${baseUrl}` : offline ? "offline (fixture intents, no LLM)" : `in-process, ${process.env.OPENAI_MODEL || "gpt-4.1-mini"}`;
console.log(`\nToday: ${today.toISODate()} (${today.weekdayLong}) Asia/Riyadh — mode: ${mode}\n`);

for (const s of SCENARIOS) {
  const result = await send(s.userId, s.message, deps);
  results[s.id] = result;
  const failures = checkScenario(s.id, result, today, results);
  if (failures.length === 0) passed++;

  const status = failures.length === 0 ? "PASS" : "FAIL";
  console.log(`${status} ${s.id}  [${s.sender} #${s.userId}] ${s.message}`);
  console.log(`      expected: ${s.expected}`);
  console.log(`      action:   ${result.action}${result.task_id ? ` (task_id ${result.task_id})` : ""}${result.reason ? ` — ${result.reason}` : ""}`);
  console.log(`      reply:    ${result.reply.replace(/\n/g, "\n                ")}`);
  for (const f of failures) console.log(`      ✗ ${f}`);
  console.log();

  const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, "<br>");
  rows.push(
    `| ${s.id} | ${s.sender} (${s.userId}) | ${cell(s.message)} | ${cell(s.expected)} | \`${result.action}\`${result.task_id ? ` #${result.task_id}` : ""} | ${cell(result.reply)} | ${status} |`,
  );
}

console.log(`${passed}/${SCENARIOS.length} scenarios passed.`);

mkdirSync("docs", { recursive: true });
writeFileSync(
  "docs/scenario-results.md",
  [
    "# Scenario results (T01–T10)",
    "",
    `Generated by \`pnpm scenarios\` — today = ${today.toISODate()} (${today.weekdayLong}), Asia/Riyadh — mode: ${mode}.`,
    "",
    `**${passed}/${SCENARIOS.length} passed.**`,
    "",
    "| # | Sender | Message | Expected | Action | Reply | Result |",
    "|---|---|---|---|---|---|---|",
    ...rows,
    "",
  ].join("\n"),
);
console.log("Report written to docs/scenario-results.md");

await awaitAllCallbacks();
process.exit(passed === SCENARIOS.length ? 0 : 1);
